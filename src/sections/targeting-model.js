/** Угол между соседними иконками на диске: шесть способов по кругу. */
export const SLOT_DEG = 60;

/**
 * Угол поворота диска, при котором пункт i стоит слева (там, где у неповёрнутого диска пункт 0), — ближайший к
 * текущему from: диск идёт кратчайшим путём и не раскручивается назад на полный круг (6 → 1 — шаг вперёд).
 * При равных путях (ровно полкруга) — вперёд, то есть в сторону уменьшения угла, как при автолистании.
 */
export function turnTo(from, i, slot = SLOT_DEG) {
  const base = -slot * i;
  const k = Math.ceil((from - base) / 360 - 0.5);
  return base + 360 * k || 0;
}

/** Следующий пункт по кругу. */
export const nextIndex = (i, total) => (i + 1) % total;
